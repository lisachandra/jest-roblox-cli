/**
 * The Luau harness `ree run` executes for the emulator backend.
 *
 * Mirrors what the run-mode plugin does inside Studio, plus the ree parity
 * shims the spike (`docs/agents/offline-runtime-spike.md` in the consuming
 * repo) proved necessary:
 *
 * 1. Thread-env seeding — ree's `warn` is a VM-level global but is missing as
 *    a member of the table `getfenv(0)` returns; the runner snapshots
 *    print/warn/math.random from exactly that table for global mocks.
 * 2. `_luau-aliases` rename-back — ree skips dot-prefixed mount entries, so
 *    staging renamed them; the harness restores them before the first require.
 * 3. `getDataModelService` stand-in — ree creates `CoreScriptSyncService` but
 *    does not emulate `GetScriptFilePath`; hiding the service keeps the
 *    runner's SearchSource on the Instance-relative branch.
 * 4. `debug.loadmodule` polyfill — ree has no `debug.loadmodule` and stubs
 *    `loadstring`; the runner's `_execModule` needs one of them to execute
 *    modules. Built on `Context.StandIn` + `require`, with the env binding
 *    Studio's version provides (`getfenv(fn).script` feeds `dmScript`).
 *
 * `@rbxts/react/tags.lua` is handled at staging time (regenerated from the
 * ree reflection dump) rather than here, so rur runs get the same fix without
 * a harness.
 *
 * The harness ends with `@done` (ree's early-end marker) and reports the
 * envelope through a `@JEST_RESULTS ` line the backend parses from the run's
 * output. Failed tests do NOT error the harness — the envelope carries them
 * so the CLI reports them as ordinary Jest failures. Only a rejected
 * `runCLI` (runner crash) errors the run.
 */

/** Serializable global flags the harness writes before anything loads. */
export type EmulatorHarnessGlobals = Record<string, boolean | number | string>;

/**
 * `--context` payload the backend hands the harness.
 */
export interface EmulatorHarnessContext {
	/** Jest's `ci` mode flag. */
	ci: boolean;
	/** Whether the run collects coverage; arms the probe-hit sink. */
	coverage?: boolean | undefined;
	/** Global flags, mirrored from the backend config for late writers. */
	globals?: EmulatorHarnessGlobals | undefined;
	/** Instance-shaped `testPathIgnorePatterns`. */
	ignorePatterns?: Array<string> | undefined;
	/** Instance-shaped `testPathPattern`. */
	pattern?: string | undefined;
	/** Slash-separated DataModel paths to discover specs under. */
	roots: Array<string>;
	/** Slash-separated DataModel path of the test runner entry module. */
	runnerPath: string;
	/** DataModel paths of setup scripts, run once before the framework. */
	setupFiles: Array<string>;
	/** Jest `testNamePattern`, when the run filters by test name. */
	testNamePattern?: string | undefined;
	/** Jest's `verbose` flag. */
	verbose: boolean;
}

/**
 * Builds the harness source. Globals serialize into the preamble; everything
 * else arrives through `Context` at run time.
 * @param globals - Consumer global flags written before the runner loads.
 * @returns The harness Luau source.
 */
export function buildEmulatorHarnessLuau(globals: EmulatorHarnessGlobals): string {
	const globalLines = Object.entries(globals).map(
		([key, value]) => `_G[${JSON.stringify(key)}] = ${luauLiteral(value)}`,
	);
	return `-- generated by jest-roblox's emulator backend; do not edit
return function(Context)
	local HttpService = game:GetService("HttpService")

${globalLines.length > 0 ? `${globalLines.join("\n")}\n` : ""}	-- ree parity gap: warn/print/math are VM-level globals but missing as members of
	-- the table getfenv(0) returns; the runner snapshots them for global mocks.
	local threadEnv = getfenv(0)
	threadEnv.warn = warn
	threadEnv.print = print
	threadEnv.math = math

	local function resolveInstance(instancePath)
		local names = string.split(instancePath, "/")
		local current = game:GetService(table.remove(names, 1))
		for _, name in names do
			current = current:WaitForChild(name)
		end
		return current
	end

	-- ree skips dot-prefixed mount entries; staging renamed them. Rename back
	-- before anything requires the alias-dependent modules.
	local descendants = game:GetDescendants()
	for _, folder in descendants do
		if folder:IsA("Folder") and folder.Name == "_luau-aliases" then
			folder.Name = ".luau-aliases"
		end
	end

	-- The Studio lane splices the global-asset containers into the place
	-- (addGlobalAssetsToPlace); the emulator lane has no place build. The
	-- asset registry and the client bootstrap index these containers at load
	-- time, so seed empty ones when the stage carries none — specs that need
	-- real templates still fail loudly on the missing child they touch.
	local ReplicatedStorage = game:GetService("ReplicatedStorage")
	for _, name in { "Animations", "UI", "VFX", "Models" } do
		if ReplicatedStorage:FindFirstChild(name) == nil then
			local stub = Instance.new("Folder")
			stub.Name = name
			stub.Parent = ReplicatedStorage
		end
	end
	local SoundService = game:GetService("SoundService")
	if SoundService:FindFirstChild("Sounds") == nil then
		local stub = Instance.new("Folder")
		stub.Name = "Sounds"
		stub.Parent = SoundService
	end

	-- ree creates CoreScriptSyncService but does not emulate GetScriptFilePath;
	-- hide it so the runner's SearchSource takes the Instance-relative branch.
	-- StandIn takes the ModuleScript INSTANCE (not the require result) and
	-- replaces its source before anything loads it — requiring here first would
	-- cache the unpatched result.
	local ok, getDataModelService = pcall(function()
		return resolveInstance("ReplicatedStorage/TS/rbxts_include/node_modules/@rbxts-js/RobloxShared/getDataModelService")
	end)
	local fakeGetDataModelServiceSource = [[
return function(service)
	if service == "CoreScriptSyncService" then
		return nil
	end
	local success, result = pcall(function()
		local s = game:GetService(service)
		local _ = s.Name
		return s
	end)
	return success and result or nil
end
]]
	if ok then
		Context.StandIn(getDataModelService, fakeGetDataModelServiceSource)
	end

	-- loadmodule polyfill: ree has no debug.loadmodule and stubs loadstring.
	-- Compile via StandIn+require on a throwaway ModuleScript; Studio's
	-- debug.loadmodule binds env.script, which the runner relies on.
	debug.loadmodule = function(m)
		local holder = Instance.new("ModuleScript")
		holder.Name = m.Name
		local source = m.Source
		-- ree mounts *.json with raw JSON text as Source; wrap via JSONDecode.
		local trimmed = string.gsub(source, "^%s+", "")
		local first = string.sub(trimmed, 1, 1)
		if first == "{" or first == "[" then
			local decoded, data = pcall(function()
				return HttpService:JSONDecode(source)
			end)
			if decoded then
				return function()
					return data
				end, nil, nil
			end
		end
		Context.StandIn(holder, "return function(...)\\n" .. source .. "\\nend")
		local fn = require(holder)
		local env = getfenv(fn)
		setfenv(fn, setmetatable({
			script = m,
			_VERSION = "Luau",
			print = print,
			warn = warn,
			math = math,
		}, { __index = env }))
		return fn, nil, nil
	end

	local runnerPath = Context.runnerPath
	local Jest = require(resolveInstance(runnerPath))

	local projects = {}
	for _, root in Context.roots do
		table.insert(projects, resolveInstance(root))
	end
	local setupFiles = {}
	for _, setupFile in Context.setupFiles do
		table.insert(setupFiles, resolveInstance(setupFile))
	end

	local argv = {
		ci = Context.ci == true,
		verbose = Context.verbose == true,
		testPathPattern = Context.pattern,
		testNamePattern = Context.testNamePattern,
		testPathIgnorePatterns = Context.ignorePatterns,
		setupFiles = setupFiles,
	}

	-- Coverage run: arm the probe-hit sink the instrumented twins' preambles
	-- write into; the payload hands it back as "runner.coverage" so the CLI's
	-- report step maps it onto the coverage manifest.
	if Context.coverage == true then
		_G.__jest_roblox_cov = {}
	end

	local status, result = Jest.runCLI(script, argv, projects):awaitStatus()
	if status == "Rejected" then
		error("emulator harness: runCLI rejected: " .. tostring(result))
	end

	-- Same envelope shape the run-mode plugin reports: one entry per project,
	-- jestOutput a nested JSON string of the Jest result plus the runner
	-- extras (coverage hits) the CLI's envelope parser knows to extract.
	local payload = { results = result.results }
	if Context.coverage == true then
		payload.runner = { coverage = _G.__jest_roblox_cov }
	end
	local jestOutput = HttpService:JSONEncode(payload)
	local envelope = HttpService:JSONEncode({
		entries = {
			{ jestOutput = jestOutput },
		},
	})
	print("@JEST_RESULTS " .. envelope)
	print("@done")
end
`;
}

function luauLiteral(value: boolean | number | string): string {
	if (typeof value === "string") {
		return JSON.stringify(value);
	}

	return value.toString();
}
